BEGIN;
CREATE TABLE IF NOT EXISTS public.calendar_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(id),
    title VARCHAR(160) NOT NULL,
    description VARCHAR(2000),
    date VARCHAR(10) NOT NULL,
    start_time VARCHAR(5),
    end_time VARCHAR(5),
    category VARCHAR(80),
    recurrence VARCHAR(10) NOT NULL,
    completed BOOLEAN NOT NULL DEFAULT FALSE,
    protected_event BOOLEAN NOT NULL DEFAULT FALSE,
    reminder_minutes INTEGER,
    source_key VARCHAR(100),
    deleted BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_calendar_events_user ON public.calendar_events(user_id);

-- A API Spring usa credencial de banco proprietaria ou com BYPASSRLS.
-- Sem policies, a Data API nao concede acesso direto a esta tabela.
ALTER TABLE public.calendar_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL PRIVILEGES ON TABLE public.calendar_events FROM PUBLIC, anon, authenticated;
DO $$
DECLARE seq text; role_name text; privilege_name text;
BEGIN
  seq := pg_get_serial_sequence('public.calendar_events', 'id');
  IF seq IS NULL THEN RAISE EXCEPTION 'Sequence de calendar_events.id ausente ou incompatível'; END IF;
  EXECUTE format('REVOKE ALL PRIVILEGES ON SEQUENCE %s FROM PUBLIC, anon, authenticated', seq::regclass);
  FOREACH role_name IN ARRAY ARRAY['anon','authenticated'] LOOP
    FOREACH privilege_name IN ARRAY ARRAY['USAGE','SELECT','UPDATE'] LOOP
      IF has_sequence_privilege(role_name, seq, privilege_name) THEN
        RAISE EXCEPTION 'Privilegio efetivo inesperado na sequence de calendario';
      END IF;
    END LOOP;
  END LOOP;
END $$;
COMMIT;
